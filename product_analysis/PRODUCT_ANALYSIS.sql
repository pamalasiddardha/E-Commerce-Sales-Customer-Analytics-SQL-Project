-- QUESTION 16:
-- HOW MANY PRODUCTS ARE AVAILABLE IN EACH PRODUCT CATEGORY?
 SELECT 
    C.CATEGORY_NAME AS CATEGORY,
    COUNT(P.PRODUCT_ID) AS TOTAL_PRODUCTS
FROM CATEGORIES C
LEFT JOIN PRODUCTS P
    ON C.CATEGORY_ID = P.CATEGORY_ID
GROUP BY C.CATEGORY_ID, C.CATEGORY_NAME;

-- =========================================================
-- QUESTION 17:
-- WHAT IS THE TOTAL QUANTITY SOLD FOR EACH PRODUCT
-- FROM COMPLETED ORDERS?
-- =========================================================
SELECT 
    P.PRODUCT_NAME,
    SUM(OT.QUANTITY) AS TOTAL_QUANTITY
FROM PRODUCTS P
LEFT JOIN ORDER_ITEMS OT
    ON P.PRODUCT_ID = OT.PRODUCT_ID
JOIN ORDERS O
    ON OT.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'COMPLETED'
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME;

-- =========================================================
-- QUESTION 18:
-- WHICH PRODUCT GENERATED THE HIGHEST REVENUE
-- FROM COMPLETED ORDERS?
-- =========================================================
SELECT 
    P.PRODUCT_NAME,
    SUM(OT.QUANTITY * OT.UNIT_PRICE) AS HIGHEST_REVENUE
FROM PRODUCTS P
LEFT JOIN ORDER_ITEMS OT
    ON P.PRODUCT_ID = OT.PRODUCT_ID
JOIN ORDERS O
    ON OT.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'COMPLETED'
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY HIGHEST_REVENUE DESC
LIMIT 1;

-- =========================================================
-- QUESTION 19:
-- WHICH ARE THE TOP 5 PRODUCTS BY TOTAL QUANTITY SOLD
-- FROM COMPLETED ORDERS?
-- =========================================================
SELECT 
    P.PRODUCT_NAME,
    SUM(OT.QUANTITY) AS TOTAL_QUANTITY
FROM PRODUCTS P
LEFT JOIN ORDER_ITEMS OT
    ON P.PRODUCT_ID = OT.PRODUCT_ID
JOIN ORDERS O
    ON OT.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'COMPLETED'
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME
ORDER BY TOTAL_QUANTITY DESC
LIMIT 5;

-- =========================================================
-- QUESTION 20:
-- WHAT IS THE TOTAL REVENUE GENERATED BY EACH PRODUCT CATEGORY
-- FROM COMPLETED ORDERS?
-- =========================================================
SELECT 
    C.CATEGORY_NAME,
    SUM(OT.QUANTITY * OT.UNIT_PRICE) AS TOTAL_REVENUE
FROM CATEGORIES C
JOIN PRODUCTS P
    ON C.CATEGORY_ID = P.CATEGORY_ID
LEFT JOIN ORDER_ITEMS OT 
    ON P.PRODUCT_ID = OT.PRODUCT_ID
JOIN ORDERS O
    ON OT.ORDER_ID = O.ORDER_ID
WHERE O.ORDER_STATUS = 'COMPLETED'
GROUP BY C.CATEGORY_ID, C.CATEGORY_NAME;

-- =========================================================
-- QUESTION 21:
-- WHAT IS THE AVERAGE PRODUCT PRICE FOR EACH CATEGORY?
-- =========================================================
SELECT 
    C.CATEGORY_NAME,
    ROUND(AVG(P.UNIT_PRICE), 2) AS AVERAGE_PRODUCT_PRICE
FROM CATEGORIES C
LEFT JOIN PRODUCTS P
    ON C.CATEGORY_ID = P.CATEGORY_ID
GROUP BY C.CATEGORY_ID, C.CATEGORY_NAME;

-- =========================================================
-- QUESTION 22:
-- WHICH PRODUCTS HAVE NEVER BEEN SOLD IN A COMPLETED ORDER?
-- =========================================================
SELECT 
    P.PRODUCT_NAME
FROM PRODUCTS P
LEFT JOIN ORDER_ITEMS OT
    ON P.PRODUCT_ID = OT.PRODUCT_ID
LEFT JOIN ORDERS O
    ON OT.ORDER_ID = O.ORDER_ID
    AND O.ORDER_STATUS = 'COMPLETED'
WHERE O.ORDER_ID IS NULL
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME;